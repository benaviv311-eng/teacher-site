export const LETTERS = ['א', 'ב', 'ג'];

export function scoreResponses(answers) {
  const totals = { Cooler: 0, Closer: 0, Cleaner: 0 };
  QUESTIONS.forEach((question, index) => {
    const option = question.options[LETTERS.indexOf(answers[index])];
    if (option) totals[option.type] += 1;
  });
  return totals;
}

export function describeProfile(scores) {
  const ordered = [...TYPES].sort((a, b) => scores[b] - scores[a]);
  const mixed = scores[ordered[0]] - scores[ordered[1]] <= 1;
  return { type: mixed ? 'משולב' : ordered[0], ranked: ordered };
}
